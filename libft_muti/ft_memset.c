#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t		i;
	char		*schar;

	i = 0;
	schar = s;
	while (i < n)
	{
		schar[i] = c;
		i++;
	}
	return (s);
}
